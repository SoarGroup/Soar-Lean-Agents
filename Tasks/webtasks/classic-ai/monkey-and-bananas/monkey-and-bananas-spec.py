# Monkey and bananas: WorldSpec description (statement numbers as in english-input.txt).
from worldspec_py import *
M = obj('m', 'animal')
TASK = task(
  name='monkey-and-bananas', title='Monkey and bananas (monkey-and-bananas)', folder='classic-ai/monkey-and-bananas',
  lean_name='monkeyBananas',
  statements=[
    (1, 'There are three places in a room: A, B and C.'),
    (2, 'A monkey is at A. A box is at C. Bananas hang from the ceiling above B.'),
    (3, 'The monkey is on the floor.'),
    (4, 'The monkey can go from its place to another place if it is on the floor.'),
    (5, "The monkey can push the box from its place to another place if the box is at the monkey's place and the monkey is on the floor. The monkey and the box both end at the new place."),
    (6, "The monkey can climb onto the box if the box is at the monkey's place and the monkey is on the floor."),
    (7, 'The monkey can climb down from the box onto the floor.'),
    (8, 'The monkey can grasp the bananas if it is on the box and the box is at the place under the bananas.'),
    (9, 'The goal is that the monkey has the bananas.')],
  world_rels=['at', 'on', 'holds'],
  ops=[
    dict(name='go', params=[('to', 'location')], stmts=[4],
         pre=[M, rel('on', V('m'), H('floor')), rel('at', V('m'), V('from')), distinct('from', 'to')],
         bind=[M, rel('at', V('m'), V('old'))],
         effects=[e_change('at', [V('m'), V('old')], 2, V('to'))],
         report=[text('Go to '), handle('to')]),
    dict(name='push', params=[('to', 'location')], stmts=[5],
         pre=[M, obj('bx', 'box'), rel('on', V('m'), H('floor')), rel('at', V('m'), V('p')), rel('at', V('bx'), V('p')), distinct('p', 'to')],
         bind=[M, obj('bx', 'box'), rel('at', V('m'), V('old')), rel('at', V('bx'), V('old'))],
         effects=[e_change('at', [V('m'), V('old')], 2, V('to')), e_change('at', [V('bx'), V('old')], 2, V('to'))],
         report=[text('Push the box to '), handle('to')]),
    dict(name='climb-up', params=[('bx', 'box')], stmts=[6],
         pre=[M, rel('on', V('m'), H('floor')), rel('at', V('m'), V('p')), rel('at', V('bx'), V('p'))],
         bind=[M],
         effects=[e_change('on', [V('m'), H('floor')], 2, V('bx'))],
         report=[text('Climb onto '), handle('bx')]),
    dict(name='climb-down', params=[('f', 'floor')], stmts=[7],
         pre=[M, obj('bx', 'box'), rel('on', V('m'), V('bx'))],
         bind=[M, obj('bx', 'box'), rel('on', V('m'), V('bx'))],
         effects=[e_change('on', [V('m'), V('bx')], 2, V('f'))],
         report=[text('Climb down onto '), handle('f')]),
    dict(name='grasp', params=[('fd', 'food')], stmts=[8],
         pre=[M, obj('bx', 'box'), rel('on', V('m'), V('bx')), rel('at', V('bx'), V('p')), rel('at', V('fd'), V('p'))],
         bind=[M],
         effects=[e_add('holds', V('m'), V('fd'))],
         report=[text('Grasp '), handle('fd')])],
  goal=ex(M, obj('fd', 'food'), rel('holds', V('m'), V('fd'))), goalStmts=[9],
  assumptions=[
    dict(id='A-MB1', kind='intent', stmts=[2, 8], text='"Bananas hang from the ceiling above B": the bananas are at B, so "the place under the bananas" is the place the bananas are at.'),
    dict(id='A-MB2', kind='intent', stmts=[3, 6, 7], text='The floor is an object; being on the floor or on the box is an on relation from the monkey.'),
    dict(id='A-MB3', kind='intent', stmts=[8, 9], text='"has the bananas" is a holds relation from the monkey to the bananas, added by grasp.'),
    dict(id='A-MB4', kind='intent', stmts=[4, 5, 6, 7, 8], text='The actions are named go, push, climb-up, climb-down and grasp.')])
