"""Write generated agents (agentgen JSON) as VisualSoar projects.

usage: python3 -I tools/vsproject.py GEN.json OUTDIR [DEFAULT_DIR]

For each variant V: OUTDIR/V/V.soar (load file), OUTDIR/V/V.vsa.json (VisualSoar 9.6 project,
format version 6: layout and datamap), OUTDIR/V/V/ (the project folder: one file per operator,
an `elaborations` folder, `_source.soar` files), and, for look-ahead variants, OUTDIR/V/default/
(Soar's default selection library, copied from DEFAULT_DIR). Also OUTDIR/V/english.md.
"""
import json, os, shutil, sys
from collections import OrderedDict

HEADER = "# Generated by agentgen from the Lean description ({variant}). Do not edit: change the\n" \
         "# description and regenerate. Hand-written rules go in raw files listed as escape hatches.\n\n"


def tree(files):
    """Nested dict: folder -> {'files': [...], 'dirs': OrderedDict}."""
    root = {'files': [], 'dirs': OrderedDict()}
    for f in files:
        parts = f['path'].split('/')
        node = root
        for d in parts[:-1]:
            node = node['dirs'].setdefault(d, {'files': [], 'dirs': OrderedDict()})
        node['files'].append(dict(f, base=parts[-1]))
    return root


def write_folder(node, path, name, variant, layout_children, ids, selection):
    os.makedirs(path, exist_ok=True)
    src = []
    files = sorted(node['files'], key=lambda f: (f['base'] != '_firstload.soar',))
    hl = {f['base'][:-5] for f in files if f['kind'].startswith('HIGH_LEVEL')}
    # _firstload first, then plain folders, then files (high-level ones with their folders)
    for f in files:
        if f['base'] != '_firstload.soar':
            continue
        body = '\n'.join(f['cmds'])
        if selection:
            body += '\n\npushd ../default\nsource selection.soar\npopd\n'
        open(os.path.join(path, f['base']), 'w').write(HEADER.format(variant=variant) + body + '\n')
        src.append('source _firstload.soar')
        layout_children.append({'type': 'FILE_OPERATOR', 'id': ids(), 'name': '_firstload',
                                'file': '_firstload.soar', 'children': []})
    for d, sub in node['dirs'].items():
        if d in hl:
            continue
        kids = []
        write_folder(sub, os.path.join(path, d), d, variant, kids, ids, False)
        src += [f'pushd {d}', f'source {d}_source.soar', 'popd']
        layout_children.append({'type': 'FOLDER', 'id': ids(), 'name': d, 'folder': d, 'children': kids})
    for f in files:
        if f['base'] == '_firstload.soar':
            continue
        text = HEADER.format(variant=variant) + '\n\n'.join(f['rules']) + ('\n' if f['rules'] else '')
        if f['cmds']:
            text += '\n'.join(f['cmds']) + '\n'
        open(os.path.join(path, f['base']), 'w').write(text)
        src.append(f'source {f["base"]}')
        stem = f['base'][:-5]
        entry = {'type': f['kind'], 'id': ids(), 'name': stem, 'file': f['base'], 'children': []}
        if stem in hl:
            sub = node['dirs'].get(stem, {'files': [], 'dirs': OrderedDict()})
            write_folder(sub, os.path.join(path, stem), stem, variant, entry['children'], ids, False)
            src += [f'pushd {stem}', f'source {stem}_source.soar', 'popd']
        layout_children.append(entry)
    open(os.path.join(path, f'{name}_source.soar'), 'w').write('\n'.join(src) + '\n')


def datamap(v):
    s = v['schema']
    verts, by = [], {}

    def add(vid, **kw):
        if vid not in by:
            by[vid] = dict(id=vid, **kw)
            verts.append(by[vid])
        return vid

    def vtype(t, owner, attr):
        if t['kind'] == 'int':
            return add('int', type='INTEGER')
        if t['kind'] == 'obj':
            return t['type']
        return add(f'{owner}-{attr}', type='ENUMERATION', choices=t['choices'])

    add('int', type='INTEGER')
    for ty in s['types']:
        add(ty['name'], type='SOAR_ID', outEdges=[
            {'name': a['name'], 'toId': vtype(a['type'], ty['name'], a['name']),
             'comment': a['doc'] + (' (derived)' if a['derived'] else '')} for a in ty['attrs']])
    names = [s['task']] + [f['path'].split('/')[0] for f in v['files'] if f['kind'].startswith('HIGH_LEVEL')]
    add('state-name', type='ENUMERATION', choices=sorted(set(names)))
    add('op-name', type='ENUMERATION', choices=['initialize-' + s['task']] + v['ops'])
    add('nil', type='ENUMERATION', choices=['nil'])
    params = {}
    for f in v['files']:
        for r in f['rules']:
            for line in r.split('\n'):
                if line.strip().startswith('(<o> ^') and '<' in line.split('^', 1)[1]:
                    a = line.split('^', 1)[1].split()[0]
                    if a not in ('name',):
                        params[a] = True
    holder = {a['name']: a['type'].get('type') for a in s['state'] if a['type']['kind'] == 'obj'}
    add('operator', type='SOAR_ID', outEdges=[{'name': 'name', 'toId': 'op-name', 'comment': ''}] +
        [{'name': p, 'toId': next(iter(holder.values())), 'comment': 'parameter'} for p in params])
    add('desired', type='SOAR_ID', outEdges=[{'name': h, 'toId': t, 'comment': 'goal object'}
                                             for h, t in holder.items()])
    edges = [{'name': 'name', 'toId': 'state-name', 'comment': ''},
             {'name': 'superstate', 'toId': 'nil', 'comment': ''},
             {'name': 'operator', 'toId': 'operator', 'comment': ''},
             {'name': 'desired', 'toId': 'desired', 'comment': ''},
             {'name': 'success', 'toId': 'desired', 'comment': 'goal reached'}]
    edges += [{'name': a['name'], 'toId': vtype(a['type'], 'state', a['name']), 'comment': a['doc']}
              for a in s['state']]
    add('state', type='SOAR_ID', outEdges=edges)
    return {'rootId': 'state', 'vertices': verts}


def main():
    gen, out = sys.argv[1], sys.argv[2]
    default = sys.argv[3] if len(sys.argv) > 3 else None
    for v in json.load(open(gen)):
        name = v['name']
        base = os.path.join(out, name)
        if os.path.exists(base):
            shutil.rmtree(base)
        os.makedirs(base)
        counter = iter(range(1, 10000))
        ids = lambda: str(next(counter))
        children = []
        write_folder(tree(v['files']), os.path.join(base, name), name, name, children, ids, v['selection'])
        open(os.path.join(base, name + '.soar'), 'w').write(f'pushd {name}\nsource {name}_source.soar\npopd\n')
        vsa = {'version': '6', 'datamap': datamap(v),
               'layout': {'type': 'OPERATOR_ROOT', 'id': '0', 'name': name, 'folder': name, 'children': children}}
        json.dump(vsa, open(os.path.join(base, name + '.vsa.json'), 'w'), indent=2)
        open(os.path.join(base, 'english.md'), 'w').write(v['english'])
        if v['selection']:
            if not default:
                sys.exit('look-ahead variant needs DEFAULT_DIR')
            shutil.copytree(default, os.path.join(base, 'default'))
        print(name, 'written')


if __name__ == '__main__':
    main()
